"""Extract a fixed NASA EIC frame and count its displayed color classes."""
import argparse
import hashlib
import io
import json
from pathlib import Path
import subprocess
from urllib.request import urlopen

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
MEDIA = ROOT / "site" / "media"
URL = "https://svs.gsfc.nasa.gov/vis/a000000/a005300/a005313/nightlights_flat_series_and_change_wZooms_13_EIC_2160p30_h265.mp4"
SHA256 = "fa770691e32961d6670ef22689a63210fd732228fabf4946a8117e96b2bcffd9"
LIMIT = 36 * 1024 * 1024
SIZE = (7680, 2160)
SECOND = 42
BANDS = 12
# Half-open pixel boxes inspected on this frame. The inset labels, borders,
# connections to the map and the legend sit outside these windows.
REGIONS = {
    "europe": [696, 820, 1980, 2040],
    "med": [2390, 200, 3216, 1256],
    "ukraine": [4656, 174, 5712, 908],
    "india": [6068, 1144, 7068, 2080],
}


def digest(data):
    return hashlib.sha256(data).hexdigest()


def classify(pixels, threshold):
    r, g, b = np.moveaxis(pixels.astype(np.int16), -1, 0)
    purple = (b >= 32) & (b - g >= threshold) & (r - g >= 3) & (b - r >= -3)
    orange = (r >= 36) & (r - g >= threshold) & (g - b >= 5)
    return int(purple.sum()), int(orange.sum())


def build(frame):
    if frame.size != SIZE or frame.mode != "RGB":
        raise ValueError("Unexpected frame dimensions or format")
    files = {"night-lights.webp": frame.resize((2560, 720), Image.Resampling.LANCZOS)}
    regions = []
    for region, box in REGIONS.items():
        crop = frame.crop(box)
        files[region + ".webp"] = crop
        pixels = np.asarray(crop)
        bands = []
        for index in range(BANDS):
            start = index * crop.width // BANDS
            end = (index + 1) * crop.width // BANDS
            values = pixels[:, start:end]
            bright, dim = classify(values, 12)
            bands.append({"start": start, "end": end, "pixels": values.shape[0] * values.shape[1],
                          "bright": bright, "dim": dim})
        regions.append({"id": region, "box": box, "image": region + ".webp", "bands": bands,
                        "sensitivity": {str(t): list(classify(pixels, t)) for t in (10, 12, 14)}})

    manifest = {"schema": 1, "svs": 5313, "source": "https://svs.gsfc.nasa.gov/5313/",
                "video": URL, "sourceSha256": SHA256, "frame": SECOND * 30, "second": SECOND,
                "width": SIZE[0], "height": SIZE[1], "classifier": "rgb-visible-change-v1",
                "rawRgbSha256": digest(frame.tobytes()), "regions": regions, "media": {}}
    assets = {}
    for name, image in files.items():
        buffer = io.BytesIO()
        image.save(buffer, format="WEBP", quality=91, method=5)
        assets[name] = buffer.getvalue()
        manifest["media"][name] = digest(assets[name])
    assets["night-lights.json"] = (json.dumps(manifest, indent=2) + "\n").encode("utf-8")
    return manifest, assets


def main():
    release = ROOT / "release"
    release.mkdir(exist_ok=True)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("video", type=Path, nargs="?", default=release / "source.mp4")
    parser.add_argument("--check", action="store_true", help="Verify the generated bytes without replacing site files")
    args = parser.parse_args()
    video = args.video
    if not video.exists():
        with urlopen(URL, timeout=35) as response:
            data = response.read(LIMIT + 1)
        if len(data) > LIMIT or digest(data) != SHA256:
            raise ValueError("NASA video did not match the bounded source")
        video.write_bytes(data)
    if video.stat().st_size > LIMIT or digest(video.read_bytes()) != SHA256:
        raise ValueError("Unexpected video bytes")

    command = ["ffmpeg", "-v", "error", "-threads", "4", "-ss", str(SECOND), "-i", str(video),
               "-frames:v", "1", "-f", "image2pipe", "-c:v", "png", "pipe:1"]
    frame = Image.open(io.BytesIO(subprocess.check_output(command))).convert("RGB")
    manifest, assets = build(frame)
    for name, content in assets.items():
        file = MEDIA / name
        if args.check:
            old = file.read_bytes()
            if name.endswith(".json"):
                old = old.replace(b"\r\n", b"\n")
            if old != content:
                raise ValueError("Generated asset differs: " + name)
        else:
            temporary = file.with_suffix(file.suffix + ".writing")
            temporary.write_bytes(content)
            temporary.replace(file)
    for region in manifest["regions"]:
        print(region["id"], region["sensitivity"])


if __name__ == "__main__":
    main()
